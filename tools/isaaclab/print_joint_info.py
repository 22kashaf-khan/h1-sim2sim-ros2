"""Print the H1 joint order and per-joint settings as Isaac Lab resolves them,
and optionally write them as a deployment config (--output)."""

import argparse

import yaml

from isaaclab.app import AppLauncher

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--task", default="Isaac-Velocity-Flat-H1-v0")
parser.add_argument("--output", default=None, help="write the deployment config YAML to this path")
AppLauncher.add_app_launcher_args(parser)
args = parser.parse_args()
args.headless = True

app_launcher = AppLauncher(args)
simulation_app = app_launcher.app

import gymnasium as gym

import isaaclab_tasks  # noqa: F401  (importing registers the tasks)
from isaaclab_tasks.utils import parse_env_cfg


def as_list(values):
    return [round(v, 6) for v in values.tolist()]


env_cfg = parse_env_cfg(args.task, device=args.device, num_envs=1)
env = gym.make(args.task, cfg=env_cfg)
robot = env.unwrapped.scene["robot"]

obs_dim = env.unwrapped.observation_manager.group_obs_dim["policy"]
act_dim = env.unwrapped.action_manager.total_action_dim
print(f"\n=== {args.task}: observation dim {obs_dim}, action dim {act_dim} ===")

print(f"{'idx':>3}  {'joint':<26} {'default':>8} {'kp':>7} {'kd':>6}")
for i, name in enumerate(robot.joint_names):
    default = robot.data.default_joint_pos[0, i].item()
    kp = robot.data.joint_stiffness[0, i].item()
    kd = robot.data.joint_damping[0, i].item()
    print(f"{i:>3}  {name:<26} {default:>8.3f} {kp:>7.1f} {kd:>6.1f}")

obs_manager = env.unwrapped.observation_manager
deploy_cfg = {
    "task": args.task,
    "physics_dt": env_cfg.sim.dt,
    "decimation": env_cfg.decimation,
    "control_period": round(env_cfg.sim.dt * env_cfg.decimation, 6),
    "action_scale": env_cfg.actions.joint_pos.scale,
    "observation_dim": int(obs_dim[0]),
    "action_dim": int(act_dim),
    "observation_terms": [
        {"name": name, "size": int(dim[0])}
        for name, dim in zip(
            obs_manager.active_terms["policy"], obs_manager.group_obs_term_dim["policy"]
        )
    ],
    "joint_names": list(robot.joint_names),
    "default_joint_pos": as_list(robot.data.default_joint_pos[0]),
    "stiffness": as_list(robot.data.joint_stiffness[0]),
    "damping": as_list(robot.data.joint_damping[0]),
}

if args.output:
    with open(args.output, "w", newline="\n") as f:
        f.write(f"# Generated by tools/isaaclab/print_joint_info.py for {args.task}.\n")
        f.write("# Do not edit by hand. Rerun the script instead.\n")
        yaml.safe_dump(deploy_cfg, f, sort_keys=False, default_flow_style=None)
    print(f"wrote {args.output}")

env.close()
simulation_app.close()