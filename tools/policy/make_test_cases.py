"""Generate reference observation/action pairs for an ONNX policy,
used to test the C++ inference code without a simulator."""

import argparse
import hashlib
from pathlib import Path

import numpy as np
import onnxruntime as ort
import yaml

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("policy_dir", type=Path, help="folder containing policy.onnx and deploy.yaml")
parser.add_argument("--num-random", type=int, default=5)
parser.add_argument("--seed", type=int, default=0)
args = parser.parse_args()

policy_dir = args.policy_dir
onnx_path = policy_dir / "policy.onnx"
deploy = yaml.safe_load((policy_dir / "deploy.yaml").read_text())
session = ort.InferenceSession(str(onnx_path))
input_name = session.get_inputs()[0].name
output_name = session.get_outputs()[0].name

offsets = {}
start = 0
for term in deploy["observation_terms"]:
    offsets[term["name"]] = slice(start, start + term["size"])
    start += term["size"]
assert start == deploy["observation_dim"], "observation terms don't add up"


def standing_obs(command=(0.0, 0.0, 0.0)):
    obs = np.zeros(deploy["observation_dim"], dtype=np.float32)
    obs[offsets["projected_gravity"]] = (0.0, 0.0, -1.0)
    obs[offsets["velocity_commands"]] = command
    return obs


def random_obs(rng):
    obs = rng.uniform(-1.0, 1.0, deploy["observation_dim"]).astype(np.float32)
    gravity = rng.normal(size=3) * 0.1 + (0.0, 0.0, -1.0)
    obs[offsets["projected_gravity"]] = gravity / np.linalg.norm(gravity)
    return obs


rng = np.random.default_rng(args.seed)
cases = {
    "standing_still": standing_obs(),
    "walk_forward": standing_obs((1.0, 0.0, 0.0)),
    "turn_left": standing_obs((0.0, 0.0, 1.0)),
}
for i in range(args.num_random):
    cases[f"random_{i}"] = random_obs(rng)

test_cases = []
for name, obs in cases.items():
    actions = session.run([output_name], {input_name: obs[None, :]})[0][0]
    test_cases.append({"name": name, "obs": obs.tolist(), "actions": actions.tolist()})
    print(f"{name:<15} max |action| = {np.abs(actions).max():.3f}")

out_path = policy_dir / "test_cases.yaml"
with out_path.open("w") as f:
    f.write("# Generated by tools/policy/make_test_cases.py. Do not edit by hand.\n")
    yaml.safe_dump(
        {
            "onnx_sha256": hashlib.sha256(onnx_path.read_bytes()).hexdigest(),
            "cases": test_cases,
        },
        f,
        sort_keys=False,
        default_flow_style=None,
    )
print(f"wrote {out_path} ({len(test_cases)} cases)")
